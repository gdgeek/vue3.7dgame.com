export function canTransitionRunnerState(
  from: RunnerState,
  to: RunnerState
): boolean {
  if (to === "FAILED_TERMINAL") {
    return FAILURE_ELIGIBLE_STATES.has(from);
  }
  return NORMAL_TRANSITIONS[from as keyof typeof NORMAL_TRANSITIONS] === to;
}

export function advanceRunnerState(
  from: RunnerState,
  to: RunnerState
): RunnerState {
  if (!canTransitionRunnerState(from, to)) {
    throw new Error(`TASK51_INVALID_STATE_TRANSITION:${from}:${to}`);
  }
  return to;
}

export type LedgerKey =
  `${EvidencePhase}|${RunnerNode}|${RunnerRole}|${EvidencePath}`;

export interface EvidenceLedgerCell {
  readonly index: number;
  readonly key: LedgerKey;
  readonly phase: EvidencePhase;
  readonly node: RunnerNode;
  readonly role: RunnerRole;
  readonly path: EvidencePath;
}

function makeLedgerKey(
  phase: EvidencePhase,
  node: RunnerNode,
  role: RunnerRole,
  path: EvidencePath
): LedgerKey {
  return `${phase}|${node}|${role}|${path}`;
}

/**
 * Builds the only permitted 56 logical evidence GETs in dispatch order.
 * OPTIONS generated by the browser are intentionally outside this ledger.
 */
export function buildEvidenceLedger(): readonly EvidenceLedgerCell[] {
  const cells: EvidenceLedgerCell[] = [];
  const append = (
    phase: EvidencePhase,
    node: RunnerNode,
    role: RunnerRole,
    path: EvidencePath
  ) => {
    const cell: EvidenceLedgerCell = Object.freeze({
      index: cells.length,
      key: makeLedgerKey(phase, node, role, path),
      phase,
      node,
      role,
      path,
    });
    cells.push(cell);
  };

  for (const node of NODES) {
    for (const role of ROLES) {
      append("readiness", node, role, "/v1/user/info");
    }
  }

  for (const node of NODES) {
    for (const role of ROLES) {
      for (const path of EVIDENCE_PATHS) {
        append("baseline", node, role, path);
      }
    }
  }

  // The node ordering is a safety property: xrteeth must be restored before
  // the bridge is allowed to dispatch the first tmrpp shadow cell.
  for (const node of NODES) {
    for (const role of ROLES) {
      for (const path of EVIDENCE_PATHS) {
        append("shadow", node, role, path);
      }
    }
  }

  if (cells.length !== 56 || new Set(cells.map(({ key }) => key)).size !== 56) {
    throw new Error("TASK51_INVALID_FIXED_LEDGER");
  }

  return Object.freeze(cells);
}

export const EVIDENCE_LEDGER = buildEvidenceLedger();

export interface EvidenceLedgerRuntime {
  readonly expectedKeys: ReadonlySet<LedgerKey>;
  readonly burnedKeys: Set<LedgerKey>;
}

export function createEvidenceLedgerRuntime(): EvidenceLedgerRuntime {
  return {
    expectedKeys: new Set(EVIDENCE_LEDGER.map(({ key }) => key)),
    burnedKeys: new Set<LedgerKey>(),
  };
}

/** Burn synchronously before fetch. Unknown and duplicate cells fail closed. */
export function burnLedgerCell(
  ledger: EvidenceLedgerRuntime,
  key: LedgerKey
): number {
  if (!ledger.expectedKeys.has(key)) {
    throw new Error(`TASK51_UNKNOWN_LEDGER_CELL:${key}`);
  }
  if (ledger.burnedKeys.has(key)) {
    throw new Error(`TASK51_DUPLICATE_LEDGER_CELL:${key}`);
  }
  ledger.burnedKeys.add(key);
  return ledger.burnedKeys.size;
}

