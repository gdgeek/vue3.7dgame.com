const matchesPattern = (value: unknown, pattern: RegExp): value is string =>
  typeof value === "string" && pattern.test(value);

/**
 * RFC-8259 JSON with recursively ASCII-sorted object keys, no insignificant
 * whitespace, UTF-8 encoding and exactly one trailing LF.
 */
export function encodeAsciiSortedCanonicalJson(value: unknown): Uint8Array {
  const render = (candidate: unknown): string => {
    if (candidate === null) return "null";
    if (typeof candidate === "boolean") return candidate ? "true" : "false";
    if (typeof candidate === "number") {
      if (!Number.isFinite(candidate)) {
        throw new Error("TASK51_CANONICAL_JSON_REJECTED");
      }
      return JSON.stringify(candidate);
    }
    if (typeof candidate === "string") return JSON.stringify(candidate);
    if (Array.isArray(candidate)) {
      return `[${candidate.map((entry) => render(entry)).join(",")}]`;
    }
    if (!isPlainRecord(candidate)) {
      throw new Error("TASK51_CANONICAL_JSON_REJECTED");
    }
    const keys = Object.keys(candidate).sort();
    if (keys.some((key) => !/^[\x20-\x7E]+$/.test(key))) {
      throw new Error("TASK51_CANONICAL_JSON_REJECTED");
    }
    return `{${keys
      .map((key) => `${JSON.stringify(key)}:${render(candidate[key])}`)
      .join(",")}}`;
  };

  return new TextEncoder().encode(`${render(value)}\n`);
}

function bytesEqual(left: Uint8Array, right: Uint8Array): boolean {
  return (
    left.byteLength === right.byteLength &&
    left.every((byte, index) => byte === right[index])
  );
}

