const FORBIDDEN_OUTPUT_KEY_PARTS = [
  "password",
  "passphrase",
  "token",
  "bearer",
  "authorization",
  "cookie",
  "credential",
  "secret",
  "username",
  "profile",
  "subject",
  "digest",
  "rawbody",
  "responsebody",
  "requestbody",
  "jwt",
] as const;
const SAFE_OPAQUE_DIGEST_OUTPUT_KEYS = new Set([
  "rolesubjectdigest",
  "productiondirectmatrixsubjectdigest",
]);

const MAX_SAFE_OUTPUT_DEPTH = 8;
const MAX_SAFE_OUTPUT_STRING_LENGTH = 512;

function normalizedOutputKey(key: string): string {
  return key.toLowerCase().replace(/[^a-z0-9]/g, "");
}

function hasSensitiveStringShape(value: string): boolean {
  if (value.length > MAX_SAFE_OUTPUT_STRING_LENGTH) return true;
  if (/^(?:Bearer|Basic)\s+/i.test(value)) return true;
  // Shape-only rejection. No JWT parsing or payload inspection occurs here.
  if (/^[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/.test(value)) {
    return true;
  }
  return false;
}

/**
 * Runtime backstop for anything posted toward the page/reporting realm.
 * It intentionally accepts only JSON-safe data and rejects secret-bearing
 * names/shapes, binary bodies, exotic prototypes and cycles.
 */
export function isSafeRunnerOutput(value: unknown): boolean {
  const seen = new Set<object>();

  const visit = (candidate: unknown, depth: number): boolean => {
    if (depth > MAX_SAFE_OUTPUT_DEPTH) return false;
    if (candidate === null || typeof candidate === "boolean") return true;
    if (typeof candidate === "number") return Number.isFinite(candidate);
    if (typeof candidate === "string")
      return !hasSensitiveStringShape(candidate);
    if (typeof candidate !== "object") return false;
    if (seen.has(candidate)) return false;
    seen.add(candidate);

    if (Array.isArray(candidate)) {
      return candidate.every((entry) => visit(entry, depth + 1));
    }
    if (!isPlainRecord(candidate)) return false;

    return Object.entries(candidate).every(([key, entry]) => {
      const normalized = normalizedOutputKey(key);
      if (
        !SAFE_OPAQUE_DIGEST_OUTPUT_KEYS.has(normalized) &&
        FORBIDDEN_OUTPUT_KEY_PARTS.some((part) => normalized.includes(part))
      ) {
        return false;
      }
      return visit(entry, depth + 1);
    });
  };

  return visit(value, 0);
}

export function assertSafeRunnerOutput(
  value: unknown
): asserts value is RunnerSafeEvent {
  if (!isSafeRunnerOutput(value)) {
    throw new Error("TASK51_UNSAFE_RUNNER_OUTPUT");
  }
}
