/** Fail-closed parser for the current-Production 2x4x4x8 direct matrix raw. */
export function parseProductionDirectMatrixEvidence(
  raw: Uint8Array,
  expected: Readonly<{
    approvalRef: string;
    executionId: string;
    stageBExecutionEvidenceSha256: string;
    subjectDigest: string;
  }>
): ProductionDirectMatrixBinding {
  const reject = (): never => {
    throw new Error("TASK51_PRODUCTION_DIRECT_MATRIX_REJECTED");
  };
  if (
    !isUint8ArrayBytes(raw) ||
    raw.byteLength === 0 ||
    raw.byteLength > PRODUCTION_DIRECT_MATRIX_MAX_BYTES
  )
    reject();
  let parsed: unknown;
  try {
    parsed = JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(raw));
  } catch {
    reject();
  }
  if (!isPlainRecord(parsed)) return reject();
  const matrix = parsed;
  if (
    !hasExactObjectKeys(matrix, PRODUCTION_DIRECT_MATRIX_KEYS) ||
    matrix.schema !== PRODUCTION_DIRECT_MATRIX_SCHEMA ||
    matrix.approvalRef !== expected.approvalRef ||
    matrix.executionId !== expected.executionId ||
    matrix.environment !== "production" ||
    matrix.stageBExecutionEvidenceSha256 !==
      expected.stageBExecutionEvidenceSha256 ||
    matrix.subjectDigest !== expected.subjectDigest ||
    matrix.subjectCount !== PRODUCTION_DIRECT_MATRIX_CELL_COUNT ||
    matrix.nodeCount !== NODES.length ||
    matrix.phaseCount !== PRODUCTION_DIRECT_MATRIX_PHASES.length ||
    matrix.roleCount !== ROLES.length ||
    matrix.surfaceCount !== PRODUCTION_DIRECT_MATRIX_SURFACES.length ||
    matrix.cellCount !== PRODUCTION_DIRECT_MATRIX_CELL_COUNT ||
    matrix.ordinaryUserNegativePassed !== true ||
    matrix.rootBreakGlassPassed !== true ||
    matrix.permissionUnionAppliedCount !== 0 ||
    matrix.fallbackAppliedCount !== 0 ||
    matrix.mutationCount !== 0 ||
    matrix.unexpected5xxCount !== 0
  )
    return reject();
  const capturedAtCandidate = matrix.capturedAt;
  if (!isExactIsoInstant(capturedAtCandidate)) return reject();
  const capturedAt = capturedAtCandidate;
  const roleSubjectDigestCandidate = matrix.roleSubjectDigests;
  if (
    !isPlainRecord(roleSubjectDigestCandidate) ||
    !hasExactObjectKeys(roleSubjectDigestCandidate, ROLES)
  )
    return reject();
  const roleSubjectDigestRecord = roleSubjectDigestCandidate;
  const roleSubjectDigests: Record<RunnerRole, string> = {
    user: "",
    manager: "",
    admin: "",
    root: "",
  };
  for (const role of ROLES) {
    const digest = roleSubjectDigestRecord[role];
    if (
      typeof digest !== "string" ||
      !/^[a-f0-9]{64}$/.test(digest) ||
      digest === "0".repeat(64)
    )
      return reject();
    roleSubjectDigests[role] = digest;
  }
  const digests = ROLES.map((role) => roleSubjectDigests[role]);
  if (new Set(digests).size !== ROLES.length) return reject();
  const expectedNodePhases = NODES.flatMap((node) =>
    PRODUCTION_DIRECT_MATRIX_PHASES.map((phase, index) => ({
      node,
      ordinal: index + 1,
      phase,
    }))
  );
  const nodePhases = matrix.nodePhases;
  if (
    !Array.isArray(nodePhases) ||
    nodePhases.length !== expectedNodePhases.length
  )
    return reject();
  const nodePhaseRefs: string[] = [];
  const nodePhaseTimes: number[] = [];
  for (let index = 0; index < expectedNodePhases.length; index += 1) {
    const entry = nodePhases[index];
    const wanted = expectedNodePhases[index];
    if (
      !isPlainRecord(entry) ||
      !hasExactObjectKeys(entry, PRODUCTION_DIRECT_MATRIX_NODE_PHASE_KEYS) ||
      entry.node !== wanted.node ||
      entry.phase !== wanted.phase ||
      entry.ordinal !== wanted.ordinal ||
      !isExactIsoInstant(entry.observedAt) ||
      typeof entry.expectedBackendPublishSha !== "string" ||
      !/^[a-f0-9]{40}$/.test(entry.expectedBackendPublishSha) ||
      entry.observedBackendPublishSha !== entry.expectedBackendPublishSha ||
      entry.backendPublishShaExact !== true ||
      typeof entry.expectedIdentityPublishSha !== "string" ||
      !/^[a-f0-9]{40}$/.test(entry.expectedIdentityPublishSha) ||
      entry.observedIdentityPublishSha !== entry.expectedIdentityPublishSha ||
      entry.identityPublishShaExact !== true ||
      entry.sourceExact !== true ||
      entry.runtimeExact !== true ||
      entry.backendHealthy !== true ||
      entry.identityHealthy !== true ||
      entry.publicHealthPassed !== true ||
      entry.authzMode !== (wanted.phase === "hit" ? "shadow" : "legacy") ||
      entry.backendRouteIntegrationEnabled !== (wanted.phase === "hit") ||
      entry.responseProvider !== "legacy" ||
      entry.legacyResponseParityMatched !== true ||
      entry.permissionUnionAppliedCount !== 0 ||
      entry.fallbackAppliedCount !== 0 ||
      entry.mutationCount !== 0 ||
      entry.unexpected5xxCount !== 0 ||
      !isProductionMatrixEvidenceRef(entry.evidenceRef)
    )
      return reject();
    nodePhaseRefs.push(entry.evidenceRef);
    nodePhaseTimes.push(Date.parse(entry.observedAt));
  }
  if (new Set(nodePhaseRefs).size !== nodePhaseRefs.length) return reject();
  for (let nodeIndex = 0; nodeIndex < NODES.length; nodeIndex += 1) {
    const first = nodeIndex * PRODUCTION_DIRECT_MATRIX_PHASES.length;
    const times = nodePhaseTimes.slice(
      first,
      first + PRODUCTION_DIRECT_MATRIX_PHASES.length
    );
    if (times.some((time, index) => index > 0 && time <= times[index - 1])) {
      return reject();
    }
  }
  if (Date.parse(capturedAt) < Math.max(...nodePhaseTimes)) return reject();
  const subjects = NODES.flatMap((node) =>
    PRODUCTION_DIRECT_MATRIX_PHASES.flatMap((phase) =>
      ROLES.flatMap((role) =>
        PRODUCTION_DIRECT_MATRIX_SURFACES.map((surface) => ({
          node,
          phase,
          role,
          surface,
        }))
      )
    )
  );
  const cells = matrix.cells;
  if (!Array.isArray(cells) || cells.length !== subjects.length) {
    return reject();
  }
  const cellRefs: string[] = [];
  for (let index = 0; index < subjects.length; index += 1) {
    const cell = cells[index];
    const subject = subjects[index];
    const ordinaryNegative =
      subject.role === "user" &&
      PRODUCTION_DIRECT_MATRIX_ORDINARY_USER_DENIED_SURFACES.has(
        subject.surface
      );
    if (
      !isPlainRecord(cell) ||
      !hasExactObjectKeys(cell, PRODUCTION_DIRECT_MATRIX_CELL_KEYS) ||
      cell.node !== subject.node ||
      cell.phase !== subject.phase ||
      cell.role !== subject.role ||
      cell.surface !== subject.surface ||
      cell.ledgerKey !==
        `${subject.node}|${subject.phase}|${subject.role}|${subject.surface}` ||
      cell.roleSubjectDigest !== roleSubjectDigests[subject.role] ||
      cell.currentProduction !== true ||
      cell.directObserved !== true ||
      cell.fresh !== true ||
      cell.expectedDecisionMatched !== true ||
      cell.legacyResponseParityMatched !== true ||
      cell.ordinaryUserPrivilegedDenied !== ordinaryNegative ||
      cell.rootBreakGlassPreserved !== (subject.role === "root") ||
      cell.permissionUnionApplied !== false ||
      cell.fallbackApplied !== false ||
      cell.mutationCount !== 0 ||
      cell.unexpected5xxCount !== 0 ||
      !isProductionMatrixEvidenceRef(cell.evidenceRef)
    )
      return reject();
    cellRefs.push(cell.evidenceRef);
  }
  if (
    new Set(cellRefs).size !== cellRefs.length ||
    new Set([...nodePhaseRefs, ...cellRefs]).size !==
      nodePhaseRefs.length + cellRefs.length ||
    !bytesEqual(raw, encodeAsciiSortedCanonicalJson(matrix))
  )
    return reject();
  return Object.freeze({
    approvalRef: expected.approvalRef,
    capturedAt,
    executionId: expected.executionId,
    roleSubjectDigests: Object.freeze({ ...roleSubjectDigests }),
    stageBExecutionEvidenceSha256: expected.stageBExecutionEvidenceSha256,
    subjectDigest: expected.subjectDigest,
  });
}

