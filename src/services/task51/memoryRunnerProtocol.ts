function isPlainRecord(value: unknown): value is Record<string, unknown> {
  if (value === null || typeof value !== "object") return false;
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}

/** Requires the exact key set and primitive booleans; truthy values fail. */
export function isExactExternalGate(value: unknown): value is ExternalGate {
  if (!isPlainRecord(value)) return false;
  const actualKeys = Object.keys(value).sort();
  const expectedKeys = [...EXTERNAL_GATE_KEYS].sort();
  if (
    actualKeys.length !== expectedKeys.length ||
    actualKeys.some((key, index) => key !== expectedKeys[index])
  ) {
    return false;
  }
  return EXTERNAL_GATE_KEYS.every((key) => typeof value[key] === "boolean");
}

export function externalGatesPass(value: unknown): value is ExternalGate {
  return (
    isExactExternalGate(value) &&
    EXTERNAL_GATE_KEYS.every((key) => value[key] === true)
  );
}

