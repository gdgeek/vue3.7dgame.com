export const SCENE_NAME_FORMAT = "名称_YYYY-MM-DD_HH-mm-ss";
export const SCENE_NAME_MAX_LENGTH = 200;

const validateBaseName = (baseName: string) => {
  if (typeof baseName !== "string") {
    throw new TypeError("场景基础名称必须是字符串");
  }
  if (
    Array.from(baseName).some((character) => {
      const code = character.codePointAt(0)!;
      return code <= 0x1f || (code >= 0x7f && code <= 0x9f);
    })
  ) {
    throw new TypeError("场景基础名称不能包含控制字符");
  }
};

const withoutTimestamps = (value: string): string => {
  let name = value.trim();
  let parsed = parseSceneName(name);
  while (parsed) {
    name = parsed.baseName.trim();
    parsed = parseSceneName(name);
  }
  return name;
};

export function parseSceneName(name: string): {
  baseName: string;
  date: string;
  time: string;
  timestamp: string;
} | null {
  const match = name.match(/^(.+)_(\d{4}-\d{2}-\d{2})_(\d{2}-\d{2}-\d{2})$/u);
  if (!match) return null;

  const [, baseName, date, rawTime] = match;
  const time = rawTime.replace(/-/g, ":");
  const timestamp = `${date}T${time}`;
  // UTC is only used to validate the literal fields, not to convert their zone.
  const parsed = new Date(`${timestamp}Z`);
  if (
    Number.isNaN(parsed.getTime()) ||
    parsed.toISOString().slice(0, 19) !== timestamp
  ) {
    return null;
  }

  return { baseName, date, time, timestamp };
}

export function resolveSceneNameTimeZone(timeZone?: string): string {
  if (timeZone !== undefined && typeof timeZone !== "string") {
    throw new TypeError("时区必须是字符串");
  }
  return new Intl.DateTimeFormat("en-US", { timeZone }).resolvedOptions()
    .timeZone;
}

export function formatSceneName(
  baseName: string,
  at: Date = new Date(),
  timeZone?: string
): string {
  validateBaseName(baseName);
  const name = withoutTimestamps(baseName);
  if (!name) throw new TypeError("场景基础名称不能为空");
  if (!(at instanceof Date) || !Number.isFinite(at.getTime())) {
    throw new TypeError("场景名称时间无效");
  }

  const formatter = new Intl.DateTimeFormat("en-US", {
    timeZone: resolveSceneNameTimeZone(timeZone),
    calendar: "gregory",
    numberingSystem: "latn",
    era: "short",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hourCycle: "h23",
  });
  const parts = formatter.formatToParts(at);
  const part = (type: Intl.DateTimeFormatPartTypes) =>
    parts.find((value) => value.type === type)!.value;
  const eraYear = Number(part("year"));
  const year = part("era") === "BC" ? 1 - eraYear : eraYear;
  if (year < 0 || year > 9999) {
    throw new RangeError("场景名称年份必须使用四位数字");
  }
  const date = `${String(year).padStart(4, "0")}-${part("month")}-${part("day")}`;
  const time = `${part("hour")}-${part("minute")}-${part("second")}`;
  const formatted = `${name}_${date}_${time}`;
  if (formatted.length > SCENE_NAME_MAX_LENGTH) {
    throw new RangeError(`场景名称不能超过 ${SCENE_NAME_MAX_LENGTH} 个字符`);
  }
  return formatted;
}

/** Replace copy suffixes with this clone's timestamp; never grow a suffix chain. */
export function formatClonedSceneName(
  sourceName: string,
  copySuffix?: string,
  at: Date = new Date(),
  timeZone?: string
): string {
  validateBaseName(sourceName);
  // These are the suffixes generated by the application's translated copy UI.
  const copySuffixes = [
    copySuffix,
    " - 副本",
    " - Copy",
    " - コピー",
    " - สำเนา",
  ];
  let name = sourceName.trim();
  for (;;) {
    const previous = name;
    name = withoutTimestamps(name);
    const suffix = copySuffixes.find((value) => value && name.endsWith(value));
    if (suffix) {
      name = name.slice(0, -suffix.length).trim();
    }
    const legacy = name.match(
      /^(.*)（副本 (\d{4}-\d{2}-\d{2}) (\d{2}:\d{2}:\d{2})）$/u
    );
    if (
      legacy &&
      parseSceneName(`copy_${legacy[2]}_${legacy[3].replace(/:/g, "-")}`)
    ) {
      name = legacy[1].trim();
    }
    if (name === previous) break;
  }
  return formatSceneName(name, at, timeZone);
}
